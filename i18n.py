_IDX = {'en': 1, 'ja': 2, 'ko': 3}
_exact = {}
_templates = []
_gloss = []
_CJK = re.compile(r'[一-鿿]')


def set_lang(lang):
    global LANG, _exact, _templates, _gloss
    LANG = lang if lang in _IDX or lang == 'zh' else 'zh'
    if LANG == 'zh':
        return
    i = _IDX[LANG]
    _exact = {row[0]: row[i] for row in T}
    _templates = []
    for row in TEMPLATES:
        parts = row[0].split('{}')
        rx = re.compile('^' + '(.*?)'.join(re.escape(p) for p in parts) + '$', re.S)
        _templates.append((rx, row[i]))
    _gloss = sorted(((row[0], row[i]) for row in GLOSSARY), key=lambda x: -len(x[0]))


def tr(s):
    """Text for the screen in the current language (Chinese in, translation out)."""
    if LANG == 'zh' or not isinstance(s, str) or not _CJK.search(s):
        return s
    t = _exact.get(s)
    if t is not None:
        return t
    for rx, out in _templates:
        m = rx.match(s)
        if m:
            vals = [tr(g) for g in m.groups()]
            res = out
            for v in vals:
                res = res.replace('{}', v, 1)
            return res
    # pieces: translate known sentences inside (line by line), then the glossary
    if '\n' in s:
        return '\n'.join(tr(x) for x in s.split('\n'))
    for zh, loc in sorted(_exact.items(), key=lambda x: -len(x[0])):
        if len(zh) >= 2 and zh in s:
            s = s.replace(zh, loc)
    for zh, loc in _gloss:
        s = s.replace(zh, loc)
    return s


def system_lang():
    """Windows UI language -> zh / ja / ko / en."""
    try:
        import ctypes
        lid = ctypes.windll.kernel32.GetUserDefaultUILanguage() & 0x3FF
        return {0x04: 'zh', 0x11: 'ja', 0x12: 'ko'}.get(lid, 'en')
    except Exception:
        return 'zh'


def ui_font():
    """Font that has the glyphs of the current language."""
    return {'ko': 'Malgun Gothic', 'ja': 'Yu Gothic UI', 'en': 'Segoe UI'}.get(LANG, 'Microsoft YaHei UI')
